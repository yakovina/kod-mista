export type OptionKey = "А" | "Б" | "В" | "Г";

export interface Option {
  key: OptionKey;
  text: string;
}

export interface Source {
  label: string;
  url: string;
}

export interface Place {
  /** Місто або «Ваше місто» для загальних питань. */
  city: string;
  /** Коротка назва в родовому відмінку для «Привіт із …». */
  from: string;
  /** Три літери для поштової марки. */
  code: string;
  /** Рік або період для підпису на листівці. */
  year: string;
  /** Що зображено на листівці — підпис і alt для ілюстрації. */
  picture: string;
}

export interface Question {
  id: number; // 1..8, порядок маршруту
  topic: string;
  place: Place;
  /** Вступна фраза перед питанням (опційно). */
  context?: string;
  prompt: string;
  options: Option[];
  correct: OptionKey;
  explanation: string;
  sources: Source[];
}

export interface Level {
  slug: "tourist" | "citizen" | "keeper";
  title: string;
  /** Звання в давальному відмінку — для «Кому:» на листівці. */
  addressee: string;
  min: number;
  max: number;
  range: string;
  description: string;
  /** Ілюстрація-персонаж рівня (картинка для шеру теж). */
  character: string;
  shareText: string;
}

